    events = build_events()
    out_path = DATA_DIR / "central_bank_events.json"
    out_path.write_text(json.dumps(events, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"{len(events)}件の中央銀行イベントを保存しました -> {out_path}")
