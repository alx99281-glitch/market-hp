def build_events() -> list[dict]:
    events = []
    for date, kind, detail in FOMC_EVENTS:
        events.append({"date": date, "bank": "FRB", "type": kind, "detail": detail})
    for date, kind, detail in BOJ_EVENTS:
        events.append({"date": date, "bank": "日銀", "type": kind, "detail": detail})
    events.sort(key=lambda e: e["date"])
    return events


